#!/usr/bin/env python3
"""Read-only checks for this skill's files, Markdown links and optional snapshot."""

import argparse
import hashlib
import html
import json
from pathlib import Path
import re
import string
import sys
import unicodedata
from urllib.parse import unquote, urlsplit


IGNORED_NAMES = {'.DS_Store', '__pycache__', '.git'}
DESTINATION = r'(<[^>\n]+>|(?:\\.|[^()\s]|\([^()\n]*\))+)'
INLINE_LINK = re.compile(r'!?\[[^\]\n]*\]\(\s*' + DESTINATION
                         + r'(?:\s+[\'\"][^\n]*?[\'\"])?\s*\)')
LINK_DEFINITION = re.compile(r'^ {0,3}\[([^\]\n]+)\]:\s*' + DESTINATION, re.M)
REFERENCE_LINK = re.compile(r'!?\[([^\]\n]+)\]\[([^\]\n]*)\]')
CODE_SPAN = re.compile(r'(?<!`)(`+)(?!`)[\s\S]*?(?<!`)\1(?!`)')
MARKDOWN_ESCAPE = re.compile(r'\\([' + re.escape(string.punctuation) + r'])')


def inventory(root):
    """Do not follow directory symlinks or include generated bytecode/OS files."""
    return {p.relative_to(root).as_posix(): p for p in root.rglob('*')
            if p.is_file() and not any(part in IGNORED_NAMES
                                       for part in p.relative_to(root).parts)}


def without_fences(text):
    lines = []
    fence = None
    for line in text.splitlines():
        opening = re.match(r'^ {0,3}(`{3,}|~{3,})', line)
        if fence is None and opening:
            fence = opening[1]
            lines.append('')
        elif fence is not None:
            if re.fullmatch(r' {0,3}' + re.escape(fence[0])
                            + '{' + str(len(fence)) + r',}\s*', line):
                fence = None
            lines.append('')
        else:
            lines.append(line)
    return '\n'.join(lines)


def heading_ids(text):
    """Project Markdown headings use GitHub-style Unicode IDs, including repeats."""
    ids, used = set(), set()
    for match in re.finditer(r'^ {0,3}#{1,6}\s+(.+?)\s*#*\s*$', text, re.M):
        title = re.sub(r'!?\[([^\]]+)\]\([^)]*\)', r'\1', match[1])
        title = html.unescape(re.sub(r'<[^>]+>', '', title)).lower()
        base = ''.join(c for c in title
                       if not unicodedata.category(c).startswith(('P', 'S'))
                       or c in '-_').replace(' ', '-')
        anchor, suffix = base, 0
        while anchor in used:
            suffix += 1
            anchor = f'{base}-{suffix}'
        used.add(anchor)
        ids.add(anchor)
    ids.update(re.findall(r'<(?:a|[a-z][\w-]*)\b[^>]*\bid=[\'\"]([^\'\"]+)',
                          text, re.I))
    return ids


def markdown_links(text):
    """Check inline/image links and reference definitions; ignore fenced examples."""
    # Consume whole links before code spans inside their labels/destinations.
    # A code span enclosing a link starts earlier and masks that example instead.
    tokens = sorted((m.start(), m.end(), kind, m)
                    for kind, pattern in [('inline', INLINE_LINK), ('definition', LINK_DEFINITION),
                                          ('reference', REFERENCE_LINK), ('code', CODE_SPAN)]
                    for m in pattern.finditer(text))
    links, definitions, references = [], {}, []
    covered = -1
    normalize = lambda label: ' '.join(label.split()).casefold()
    for start, end, kind, match in tokens:
        if start < covered:
            continue
        covered = end
        if kind == 'inline':
            links.append(match[1])
        elif kind == 'definition':
            definitions.setdefault(normalize(match[1]), match[2])
        elif kind == 'reference':
            references.append(match[2] or match[1])
    links.extend(definitions.values())
    unresolved = [label for label in references if normalize(label) not in definitions]
    return links, unresolved


def field_has_value(frontmatter, field):
    """Check common scalar/block fields; full YAML validation remains separate."""
    lines = frontmatter.splitlines()
    for index, line in enumerate(lines):
        match = re.fullmatch(re.escape(field) + r':[ \t]*(.*)', line)
        if match is None:
            continue
        value = match[1].strip()
        if value.startswith(('"', "'")):
            quote = value[0]
            ending = value.rfind(quote)
            return ending > 0 and bool(value[1:ending].strip())
        value = re.split(r'[ \t]+#', value, maxsplit=1)[0].strip()
        if not value or value.startswith('#') or value.lower() in {'null', '~'}:
            return False
        if re.fullmatch(r'[|>][+-]?', value):
            for continuation in lines[index + 1:]:
                if continuation.strip() and not continuation.startswith((' ', '\t')):
                    break
                if continuation.strip():
                    return True
            return False
        return True
    return False


def checksum(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def check(root, compare=None, allow_change=(), allow_add=()):
    root = Path(root).expanduser().resolve()
    if not root.is_dir():
        raise ValueError(f'Not a skill directory: {root}')
    files = inventory(root)
    errors, documents = [], {}
    entry = files.get('SKILL.md')
    if entry is None:
        errors.append('Missing required SKILL.md')
    for relative, file in files.items():
        if not file.resolve().is_relative_to(root):
            errors.append(f'File points outside skill: {relative}')
            continue
        if file.suffix == '.md':
            try:
                documents[file.resolve()] = without_fences(file.read_text(encoding='utf-8'))
            except UnicodeError:
                errors.append(f'Not UTF-8 Markdown: {relative}')
    if entry is not None and entry.resolve() in documents:
        frontmatter = re.match(r'\A---\s*\n(.*?)\n---(?:\s*\n|$)',
                               entry.read_text(encoding='utf-8'), re.S)
        if frontmatter is None:
            errors.append('SKILL.md: missing YAML frontmatter')
        else:
            for field in ('name', 'description'):
                if not field_has_value(frontmatter[1], field):
                    errors.append(f'SKILL.md: missing {field}')
    anchors = {p: heading_ids(t) for p, t in documents.items()}
    links_checked = fragments_checked = skipped_remote = 0
    for file, text in documents.items():
        relative = file.relative_to(root).as_posix()
        links, unresolved = markdown_links(text)
        errors.extend(f'{relative}: undefined reference [{label}]' for label in unresolved)
        for link in links:
            destination = link[1:-1] if link.startswith('<') and link.endswith('>') else link
            value = html.unescape(MARKDOWN_ESCAPE.sub(r'\1', destination))
            parsed = urlsplit(value)
            if parsed.scheme or parsed.netloc:
                skipped_remote += 1
                continue
            links_checked += 1
            target = (file.parent / unquote(parsed.path)).resolve() if parsed.path else file
            if not target.is_relative_to(root):
                errors.append(f'{relative}: link outside skill: {link}')
            elif not target.exists():
                errors.append(f'{relative}: missing link target: {link}')
            elif parsed.fragment and target.suffix == '.md':
                fragments_checked += 1
                if unquote(parsed.fragment) not in anchors.get(target, set()):
                    errors.append(f'{relative}: missing heading: {link}')
    changes = None
    if compare is not None:
        baseline = Path(compare).expanduser().resolve()
        if not baseline.is_dir() or not (baseline / 'SKILL.md').is_file():
            raise ValueError(f'Not a baseline skill directory: {baseline}')
        old = inventory(baseline)
        changed = sorted(r for r in old.keys() & files.keys()
                         if checksum(old[r]) != checksum(files[r]))
        added = sorted(files.keys() - old.keys())
        removed = sorted(old.keys() - files.keys())
        changes = {'changed': changed, 'added': added, 'removed': removed}
        errors.extend(f'Unexpected change: {r}' for r in changed if r not in allow_change)
        errors.extend(f'Unexpected addition: {r}' for r in added if r not in allow_add)
        errors.extend(f'Removed baseline file: {r}' for r in removed)
    return {'root': str(root), 'files': len(files), 'markdown_files': len(documents),
            'local_links_checked': links_checked, 'heading_links_checked': fragments_checked,
            'remote_links_skipped': skipped_remote, 'snapshot_changes': changes,
            'errors': errors, 'valid': not errors}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('root', nargs='?', type=Path,
                        default=Path(__file__).resolve().parent.parent)
    parser.add_argument('--compare', type=Path, help='Read-only pre-change skill snapshot')
    parser.add_argument('--allow-change', action='append', default=[], metavar='RELATIVE_FILE')
    parser.add_argument('--allow-add', action='append', default=[], metavar='RELATIVE_FILE')
    args = parser.parse_args()
    if (args.allow_change or args.allow_add) and args.compare is None:
        parser.error('--allow-change/--allow-add require --compare')
    try:
        result = check(args.root, args.compare, args.allow_change, args.allow_add)
    except (OSError, ValueError) as error:
        print(json.dumps({'valid': False, 'errors': [str(error)]}, ensure_ascii=False))
        return 2
    print(json.dumps(result, ensure_ascii=False, indent=2))
    return 0 if result['valid'] else 1


if __name__ == '__main__':
    sys.exit(main())
